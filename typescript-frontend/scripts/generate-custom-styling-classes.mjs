import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compileString } from 'sass';

const sourcePath = fileURLToPath(new URL('../src/customstyling.scss', import.meta.url));
const outputPath = fileURLToPath(
  new URL('../src/prosemirror-editor/custom-styling.ts', import.meta.url),
);

function classNamesFromStylesheet(stylesheet) {
  const css = compileString(stylesheet).css;
  return [...new Set(
    [...css.matchAll(/\.([a-zA-Z_][\w-]*)/g)].map(([, className]) => className),
  )];
}

export function generateCustomStylingClasses() {
  const classes = classNamesFromStylesheet(readFileSync(sourcePath, 'utf8'));
  const output = [
    '// Generated by scripts/generate-custom-styling-classes.mjs. Do not edit directly.',
    'export const customStylingClasses: readonly string[] = [',
    ...classes.map((className) => `  '${className}',`),
    '];',
    '',
  ].join('\n');

  try {
    if (readFileSync(outputPath, 'utf8') === output) {
      return;
    }
  } catch {
    // Generate the allowlist when it does not exist yet.
  }
  writeFileSync(outputPath, output);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateCustomStylingClasses();
}
